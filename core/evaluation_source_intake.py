"""Isolated intake lane for user-authorized AI-generated evaluation material.

Evaluation material is useful for exercising the functional pipeline, but it
is never a human-origin blind benchmark and never enters the Human Fresh Pool.
This module shares hashing/extraction primitives with new_source_intake while
keeping the provenance gate semantically independent.
"""
from __future__ import annotations

import hashlib
import re
from pathlib import Path
from typing import Any, Iterable

from core.new_source_intake import build_source_package, normalize_source_text

EVALUATION_PROVENANCE_SCHEMA = "evaluation_source_provenance_v1"
EVALUATION_PACKAGE_SCHEMA = "evaluation_source_manifest_v1"
EVALUATION_ORIGIN = "USER_AUTHORIZED_AI_GENERATED"
EXPECTED_EVALUATION_CLASS = "EVALUATION_ONLY"
EXPECTED_AUTHORSHIP = "AI_GENERATED"
EXPECTED_GENERATION_ORIGIN = "OPENAI_CHATGPT_USER_REQUESTED"

TEST_META_PATTERNS = (
    r"这个故事为什么适合后续测试",
    r"为什么适合测试",
    r"为什么适合后续测试",
    r"(?:^|\n)\s*Scene\s*[0-9]+\s*[—-]",
    r"(?:^|\n)\s*Preserve\b",
    r"(?:^|\n)\s*测试(?:说明|分析|设计)\s*[:：]",
)


def detect_test_meta(text: str) -> list[str]:
    value = str(text or "")
    return [pattern for pattern in TEST_META_PATTERNS if re.search(pattern, value, flags=re.IGNORECASE)]


def build_evaluation_source_package(*, raw_bytes: bytes, source_path: str, source_title: str = "门外那把伞", language: str = "zh-CN", source_type: str = "txt", narrative_form: str = "SHORT_STORY", generation_origin: str = EXPECTED_GENERATION_ORIGIN, provenance_note: str = "Short story generated by ChatGPT at the user's explicit request, then explicitly selected by the user for Director V3 pipeline evaluation.") -> dict[str, Any]:
    base = build_source_package(raw_bytes=raw_bytes, source_filename=Path(source_path).name, source_origin=EVALUATION_ORIGIN, user_provided=True, source_type=source_type, source_title=source_title, language=language, encoding="utf-8")
    text = raw_bytes.decode("utf-8", errors="strict")
    return {
        "schema_version": EVALUATION_PACKAGE_SCHEMA,
        "source_package_id": base["source_package_id"],
        "source_version_id": f"{base['source_package_id']}:V01:{base['raw_source_hash'][:12]}",
        "source_path": str(Path(source_path)),
        "source_filename": base["source_filename"],
        "source_origin": EVALUATION_ORIGIN,
        "user_provided": True,
        "raw_source_hash": base["raw_source_hash"],
        "normalized_source_hash": base["normalized_source_hash"],
        "source_title": source_title,
        "language": language,
        "source_type": source_type,
        "narrative_form": narrative_form,
        "source_class": EXPECTED_EVALUATION_CLASS,
        "source_authorship": EXPECTED_AUTHORSHIP,
        "generation_origin": generation_origin,
        "user_supplied_to_system": True,
        "user_authorized_for_evaluation": True,
        "human_authored": False,
        "ai_generated": True,
        "blind_human_origin_eligible": False,
        "functional_pipeline_evaluation_eligible": True,
        "final_human_source_benchmark_eligible": False,
        "provenance_note": provenance_note,
        "project_provider_exposure": "NOT_EXPOSED_CONFIRMED",
        "source_immutable": True,
        "byte_length": len(raw_bytes),
        "normalized_text_length": len(normalize_source_text(text)),
        "text_extraction_status": base.get("text_extraction_status"),
        "lineage_state": "SOURCE_ACCEPTED",
    }


def _hashes(package: dict[str, Any]) -> set[str]:
    return {
        value
        for value in (
            str(package.get("raw_source_hash") or ""),
            str(package.get("normalized_source_hash") or ""),
        )
        if value
    }


class AuthorizedEvaluationSourceIntakeGate:
    """Fail-closed gate for the evaluation-only lane."""

    def evaluate(self, package: dict[str, Any], *, explicit_source_path: str, expected_source_path: str, existing_packages: Iterable[dict[str, Any]] = (), retired_fingerprints: Iterable[str] = (), exposed_fingerprints: Iterable[str] = (), source_text: str | None = None) -> dict[str, Any]:
        errors: list[str] = []
        actual = Path(explicit_source_path)
        expected = Path(expected_source_path)
        try:
            if actual.resolve() != expected.resolve(): errors.append("EVALUATION_SOURCE_PATH_NOT_ALLOWED")
        except OSError:
            errors.append("EVALUATION_SOURCE_PATH_INVALID")
        if package.get("schema_version") != EVALUATION_PACKAGE_SCHEMA:
            errors.append("EVALUATION_PACKAGE_SCHEMA_INVALID")
        package_path = str(package.get("source_path") or "").strip()
        if package_path:
            try:
                if Path(package_path).resolve() != expected.resolve():
                    errors.append("EVALUATION_SOURCE_PATH_MISMATCH")
            except OSError:
                errors.append("EVALUATION_SOURCE_PATH_INVALID")
        if package.get("source_filename") != expected.name:
            errors.append("EVALUATION_SOURCE_FILENAME_MISMATCH")
        raw_hash = str(package.get("raw_source_hash") or "")
        normalized_hash = str(package.get("normalized_source_hash") or "")
        if int(package.get("byte_length") or 0) <= 0 or int(package.get("normalized_text_length") or 0) <= 0: errors.append("EVALUATION_SOURCE_EMPTY")
        if package.get("source_immutable") is not True: errors.append("EVALUATION_SOURCE_NOT_IMMUTABLE")
        if package.get("source_class") != EXPECTED_EVALUATION_CLASS or package.get("source_authorship") != EXPECTED_AUTHORSHIP or package.get("generation_origin") != EXPECTED_GENERATION_ORIGIN: errors.append("EVALUATION_PROVENANCE_INCOMPLETE")
        if package.get("user_supplied_to_system") is not True or package.get("user_authorized_for_evaluation") is not True: errors.append("USER_EVALUATION_AUTHORIZATION_MISSING")
        if package.get("human_authored") is not False or package.get("ai_generated") is not True: errors.append("EVALUATION_AUTHORSHIP_CONFLICT")
        if package.get("blind_human_origin_eligible") is not False or package.get("functional_pipeline_evaluation_eligible") is not True or package.get("final_human_source_benchmark_eligible") is not False: errors.append("EVALUATION_ELIGIBILITY_INVALID")
        if package.get("source_type") != "txt" or package.get("narrative_form") != "SHORT_STORY": errors.append("EVALUATION_SOURCE_FORMAT_INVALID")
        if not re.fullmatch(r"[0-9a-f]{64}", raw_hash) or not re.fullmatch(r"[0-9a-f]{64}", normalized_hash): errors.append("EVALUATION_SOURCE_HASH_INVALID")
        if package.get("text_extraction_status") != "extracted": errors.append("EVALUATION_SOURCE_EXTRACTION_FAILED")
        if detect_test_meta(source_text or package.get("source_text") or ""): errors.append("SOURCE_CONTAINS_TEST_META")
        hashes = _hashes(package)
        retired, exposed = {str(x) for x in retired_fingerprints}, {str(x) for x in exposed_fingerprints}
        if hashes & retired: errors.append("SOURCE_RETIRED")
        if hashes & exposed: errors.append("SOURCE_PROVIDER_EXPOSED")
        if any(hashes & _hashes(item) for item in existing_packages if isinstance(item, dict)): errors.append("SOURCE_DUPLICATE")
        unique = list(dict.fromkeys(errors))
        return {"status": "AUTHORIZED_EVALUATION_SOURCE_ACCEPTED" if not unique else "NOT_ACCEPTED", "accepted": not unique, "errors": unique, "source_package_id": package.get("source_package_id"), "project_provider_exposure": "PROJECT_PROVIDER_NOT_EXPOSED" if not (hashes & exposed) else "PROJECT_PROVIDER_EXPOSED", "provider_calls": 0, "production_db_mutations": 0}


def evaluation_provenance_fingerprint(package: dict[str, Any]) -> str:
    fields = {key: package.get(key) for key in ("source_package_id", "source_class", "source_authorship", "generation_origin", "user_authorized_for_evaluation", "human_authored", "ai_generated", "blind_human_origin_eligible", "functional_pipeline_evaluation_eligible", "final_human_source_benchmark_eligible")}
    import json
    payload = json.dumps(fields, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()
